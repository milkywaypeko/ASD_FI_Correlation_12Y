"""Smoke checks for static Pages output and the raw-vs-adjusted y semantics."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"


def test_github_root_and_main_model_comparison_controls():
    root = (ROOT / "index.html").read_text(encoding="utf-8")
    html = (SITE / "index.html").read_text(encoding="utf-8")
    assert '<base href="./site/">' in root
    for field in ("compare-model-rows", "compare-all-types", "compare-all-regions",
                  "compare-export", "compare-detail-raw", "compare-detail-observations",
                  "compare-detail-export"):
        assert 'id="'+field+'"' in html
        assert 'id="'+field+'"' in root


def test_multi_scatter_uses_actual_rate_without_residualisation():
    src = (SITE / "assets/js/multivariate.js").read_text(encoding="utf-8")
    page = (SITE / "multivariate.html").read_text(encoding="utf-8")
    assert "x:value(r),y:r.rates[state.dtype]" in src
    assert "'실제 장애유형별 등록률 (%)'" in src
    assert "보정 등록률" not in src
    assert "실제 장애인 등록률" in page
    assert "조건부 예측선" in page


def test_ols_model_observation_data_consistent():
    # Confirm the sample data used by the HTML were already generated by Python.
    rows = json.loads((SITE / "data/municipalities.json").read_text(encoding="utf-8"))
    models = json.loads((SITE / "data/models_2022_after.json").read_text(encoding="utf-8"))
    current = next(m for m in models if m["scope"] == "municipal" and
                   m["region"] == "전국" and m["type"] == "자폐성")
    observations = [r for r in rows if r["year"] == 2022 and
                    r["after"] is not None and r["rates"].get("자폐성") is not None]
    assert len(observations) == current["n"] == 228
    assert current["raw"].startswith("                            OLS Regression Results")
    assert all(r["rates"]["자폐성"] >= 0 for r in observations)
